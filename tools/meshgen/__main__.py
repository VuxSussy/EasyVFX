"""meshgen: the mesh set as recipes. Shells for slashes, cones and rings, written as OBJ.

    python tools/meshgen list                 every id and its use
    python tools/meshgen build [ids ...]      write pack/meshes/<family>_<name>.obj (+ manifest.json)
    python tools/meshgen check [ids ...]      the rules below, and the files still match their recipes
    python tools/meshgen sheet [-o path]      every shell drawn with a texture, three angles each
    python tools/meshgen selftest             the rules each fail on a planted bad shell
    python tools/meshgen studio [-o path]     a Luau script that shows the set in Studio, no upload

Rules: at most 5000 triangles (Roblox allows 20000), no degenerate triangles, UVs in
0..1, the shell fits the box -0.5..0.5 with its largest side 1, and every triangle has a
reversed twin (two-sided). numpy and Pillow only.
"""

import argparse
import difflib
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))

import numpy as np  # noqa: E402

import shells  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "pack", "meshes")
MANIFEST = os.path.join(OUT, "manifest.json")
MAX_TRIS = 5000


def bank():
    with open(os.path.join(HERE, "bank.json"), encoding="utf-8") as f:
        return json.load(f)["entries"]


def ids(names=None):
    all_ids = sorted(bank())
    if not names:
        return all_ids
    out = []
    for n in names:
        key = n if n in bank() else n.replace("_", "/", 1)
        if key not in bank():
            near = difflib.get_close_matches(n, all_ids, n=3, cutoff=0.4)
            sys.exit(f"meshgen: unknown mesh {n!r}" + (f"; did you mean {', '.join(near)}?" if near else ""))
        out.append(key)
    return out


def filename(mesh_id):
    return mesh_id.replace("/", "_") + ".obj"


def render(mesh_id):
    e = bank()[mesh_id]
    p = dict(shells.DEFAULTS[e["recipe"]], **e.get("params", {}))
    return shells.RECIPES[e["recipe"]](p)


def check(verts, uvs, tris):
    fails = []
    if len(tris) > MAX_TRIS:
        fails.append(f"{len(tris)} triangles, more than {MAX_TRIS}")
    if (uvs < -1e-6).any() or (uvs > 1 + 1e-6).any():
        fails.append("UVs outside 0..1")
    lo, hi = verts.min(0), verts.max(0)
    if (np.abs(verts) > 0.5 + 1e-4).any() or abs((hi - lo).max() - 1) > 1e-3:
        fails.append(f"doesn't fit the unit box (bounds {np.round(lo, 3)} .. {np.round(hi, 3)})")
    a, b, c = verts[tris[:, 0]], verts[tris[:, 1]], verts[tris[:, 2]]
    area = np.linalg.norm(np.cross(b - a, c - a), axis=1) / 2
    if (area < 1e-9).sum():
        fails.append(f"{int((area < 1e-9).sum())} degenerate triangles")
    seen = {tuple(t) for t in tris.tolist()}
    one_sided = sum(1 for t in tris.tolist() if (t[2], t[1], t[0]) not in seen)
    if one_sided:
        fails.append(f"{one_sided} triangles without a reversed twin (one-sided)")
    return fails


def cmd_list(args):
    for i in ids(args.ids):
        v, _, t = render(i)
        print(f"{i:22s} {len(t):5d} tris  {bank()[i]['use']}")


def cmd_build(args):
    os.makedirs(OUT, exist_ok=True)
    manifest = {"note": "Generated by tools/meshgen from tools/meshgen/bank.json. Not uploaded yet.", "meshes": {}}
    if os.path.exists(MANIFEST):
        with open(MANIFEST, encoding="utf-8") as f:
            manifest = json.load(f)
    bad = 0
    for i in ids(args.ids):
        verts, uvs, tris = render(i)
        fails = check(verts, uvs, tris)
        bad += bool(fails)
        text = shells.to_obj(verts, uvs, tris, filename(i)[:-4])
        with open(os.path.join(OUT, filename(i)), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        lo, hi = verts.min(0), verts.max(0)
        manifest["meshes"][filename(i)[:-4]] = {
            "id": i, "triangles": len(tris), "bounds": [round(float(x), 4) for x in (hi - lo)],
            "sha256": hashlib.sha256(text.encode()).hexdigest(), "upload": True, "use": bank()[i]["use"],
        }
        print(f"{i:22s} {len(tris):5d} tris  " + ("ok" if not fails else "; ".join(fails)))
    manifest["meshes"] = dict(sorted(manifest["meshes"].items()))
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    return 1 if bad else 0


def cmd_check(args):
    bad = 0
    names = ids(args.ids)
    for i in names:
        path = os.path.join(OUT, filename(i))
        if not os.path.exists(path):
            print(f"{i}: not built (run `meshgen build {i}`)")
            bad += 1
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        fails = check(*shells.from_obj(text))
        verts, uvs, tris = render(i)
        if text != shells.to_obj(verts, uvs, tris, filename(i)[:-4]):
            fails.append("stale: the recipe no longer writes the committed file (run `meshgen build`)")
        if fails:
            bad += 1
            print(f"{i}: " + "; ".join(fails))
    print(f"{len(names) - bad}/{len(names)} meshes pass")
    return 1 if bad else 0


def cmd_sheet(args):
    import preview

    path = args.out or os.path.join(ROOT, ".cache", "meshgen", "sheet.png")
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    preview.sheet([(i, render(i)) for i in ids(args.ids)]).save(path)
    print(f"wrote {os.path.relpath(path)}")
    return 0


def cmd_selftest(args):
    fails = []
    for i in ids():
        got = check(*render(i))
        if got:
            fails.append(f"{i}: {'; '.join(got)}")
        v, u, t = render(i)
        back = shells.from_obj(shells.to_obj(v, u, t, "x"))
        if not (np.allclose(back[0], v, atol=1e-4) and np.allclose(back[1], u, atol=1e-4) and (back[2] == t).all()):
            fails.append(f"{i}: OBJ round trip changes the shell")
    v, u, t = render("mesh/torus")
    planted = [
        ("too many triangles", (v, u, np.concatenate([t] * 30)), "triangles"),
        ("UV outside 0..1", (v, u * 1.5, t), "UVs"),
        ("outside the unit box", (v * 1.4, u, t), "unit box"),
        ("one-sided", (v, u, t[: len(t) // 2]), "one-sided"),
        ("degenerate", (v, u, np.concatenate([t, [[0, 0, 1], [1, 0, 0]]])), "degenerate"),
    ]
    for what, shell, word in planted:
        got = check(*shell)
        if not any(word in g for g in got):
            fails.append(f"planted {what} passed ({got})")
    for f in fails:
        print("FAIL", f)
    print(f"meshgen selftest: {'ok' if not fails else str(len(fails)) + ' failed'}")
    return 1 if fails else 0


def cmd_studio(args):
    import studio

    if args.play:
        return studio.play_data(args.out or os.path.join(ROOT, ".cache", "meshgen", "play")) or 0
    return studio.main(args.out)


def main():
    ap = argparse.ArgumentParser(prog="meshgen", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name, fn in (("list", cmd_list), ("build", cmd_build), ("check", cmd_check), ("sheet", cmd_sheet)):
        p = sub.add_parser(name)
        p.add_argument("ids", nargs="*")
        if name == "sheet":
            p.add_argument("-o", "--out")
        p.set_defaults(fn=fn)
    sub.add_parser("selftest").set_defaults(fn=cmd_selftest)
    p = sub.add_parser("studio")
    p.add_argument("-o", "--out")
    p.add_argument("--play", action="store_true", help="data for baking slash_v4 with the real builder in Studio")
    p.set_defaults(fn=cmd_studio)
    args = ap.parse_args()
    return args.fn(args) or 0


if __name__ == "__main__":
    sys.exit(main())
