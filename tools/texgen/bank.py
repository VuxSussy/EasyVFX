"""The texture bank: every library v4 texture is a recipe rendered by id with knobs.

    rgba, meta = bank.render("flip/slash_erode")                  # the bank's own texture
    rgba, meta = bank.render("flip/slash_erode", seed=7)           # another take, same character
    rgba, meta = bank.render("flip/shock_ring", size=512, ease=2)  # smaller, slower to erode

Ids are `<family>/<name>`; the file is `<family>_<name>.png` in pack/generated, next to
manifest.json (the ledger script reads it: kind, size, grid, sha256, upload). Knobs are
the recipe's own (tools/texgen/recipes.py), plus size and seed for every recipe.
"""

import difflib
import hashlib
import io
import json
import os

import numpy as np
from PIL import Image

import recipes

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
BANK = os.path.join(HERE, "bank.json")
OUT = os.path.join(ROOT, "pack", "generated")
UPLOADED = os.path.join(ROOT, "pack", "textures")
MANIFEST = os.path.join(OUT, "manifest.json")
GRIDDED = ("flipbook", "sheet")


class BankError(Exception):
    pass


_bank = None


def load():
    global _bank
    if _bank is None:
        with open(BANK, encoding="utf-8") as f:
            _bank = json.load(f)
    return _bank


def ids():
    return sorted(load()["entries"])


def get(tex_id):
    e = load()["entries"].get(tex_id)
    if e is None:
        near = difflib.get_close_matches(tex_id, ids(), n=4, cutoff=0.4)
        hint = f" Did you mean {', '.join(near)}?" if near else ""
        raise BankError(f"unknown texture id {tex_id!r}.{hint} (`texgen list` shows all {len(ids())})")
    return dict(e, id=tex_id)


def resolve(names):
    """Ids from ids, file names (shape_core_flash) or families (flip)."""
    if not names:
        return ids()
    out = []
    for n in names:
        if n in load()["entries"]:
            out.append(n)
        elif n in {i.split("/")[0] for i in ids()}:
            out += [i for i in ids() if i.startswith(n + "/")]
        elif n.replace("_", "/", 1) in load()["entries"]:
            out.append(n.replace("_", "/", 1))
        else:
            get(n)
    return out


def filename(tex_id):
    return tex_id.replace("/", "_") + ".png"


def knobs(tex_id):
    e = get(tex_id)
    return dict(recipes.DEFAULTS[e["recipe"]], **e.get("params", {}))


def render(tex_id, seed=None, size=None, **edits):
    """The texture as (h, w, 4) uint8 RGBA and its meta. RGB is white unless the entry
    allows colour."""
    e = get(tex_id)
    fn = recipes.RECIPES[e["recipe"]]
    p = dict(knobs(tex_id), **edits)
    size = int(size or e["size"])
    grid = int(e.get("grid", 1))
    rng = np.random.default_rng(int(e["seed"] if seed is None else seed))
    out = fn(p, rng, size // grid if e["kind"] in GRIDDED else size)
    rgb = None
    if isinstance(out, dict):
        rgb, out = out.get("rgb"), out["alpha"]
    if isinstance(out, list):
        frames = len(out)
        out = _atlas(out, grid)
    else:
        frames = 1
    alpha = np.clip(np.asarray(out, np.float32), 0, 1)
    if rgb is None or e.get("rgb") != "spectrum":
        rgb = np.ones(alpha.shape + (3,), np.float32)
    rgba = np.concatenate([np.clip(rgb, 0, 1), alpha[..., None]], -1)
    rgba = np.round(rgba * 255).astype(np.uint8)
    meta = {"id": tex_id, "kind": e["kind"], "size": [rgba.shape[1], rgba.shape[0]], "grid": grid,
            "frames": frames, "seed": int(e["seed"] if seed is None else seed), "edits": edits}
    return rgba, meta


def _atlas(cells, grid):
    h, w = cells[0].shape
    out = np.zeros((h * grid, w * grid), np.float32)
    for i, c in enumerate(cells[: grid * grid]):
        r, k = divmod(i, grid)
        out[r * h : (r + 1) * h, k * w : (k + 1) * w] = c
    return out


def png_bytes(rgba):
    buf = io.BytesIO()
    Image.fromarray(rgba, "RGBA").save(buf, "PNG", optimize=True)
    return buf.getvalue()


def read(tex_id):
    path = os.path.join(OUT, filename(tex_id))
    if not os.path.exists(path):
        return None
    return np.asarray(Image.open(path).convert("RGBA"))


def write(results):
    """Writes the PNGs and merges their rows into manifest.json."""
    os.makedirs(OUT, exist_ok=True)
    manifest = {"library": "v4", "note": "Generated by tools/texgen from tools/texgen/bank.json. Not uploaded yet: uploads go through the ledger script after review.", "textures": {}}
    if os.path.exists(MANIFEST):
        with open(MANIFEST, encoding="utf-8") as f:
            manifest = json.load(f)
    for rgba, meta in results:
        data = png_bytes(rgba)
        name = filename(meta["id"])
        with open(os.path.join(OUT, name), "wb") as f:
            f.write(data)
        e = get(meta["id"])
        manifest["textures"][name[:-4]] = {
            "id": meta["id"], "kind": meta["kind"], "size": meta["size"], "grid": meta["grid"],
            "frames": meta["frames"], "role": e.get("role"), "upload": e.get("upload", True),
            "rgb": e.get("rgb", "white"), "sha256": hashlib.sha256(data).hexdigest(), "use": e.get("use", ""),
        }
    manifest["textures"] = dict(sorted(manifest["textures"].items()))
    with open(MANIFEST, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
